import React from 'react';
const h = React.createElement;

export function PairingPanel({ controller }) {
  const s = React.useSyncExternalStore(controller.subscribe, controller.getSnapshot, controller.getSnapshot);
  const id = React.useId();
  const snapshot = s.snapshot;
  const environment = s.environment;
  const localNetwork = environment?.localNetwork;
  const field = (key, label, placeholder) => h('label', { htmlFor: `${id}-${key}`, style: { display: 'grid', gap: 4 } }, label,
    h('input', { id: `${id}-${key}`, value: s[key], placeholder, maxLength: key === 'deviceId' ? 12 : 384,
      disabled: s.busy || (key === 'deviceId' && !!snapshot?.deviceId) || (key === 'localUrl' && s.withoutLan),
      onChange: e => controller.edit(key, e.target.value) }));
  return h('fieldset', { style: { display: 'grid', gap: 12 }, 'aria-label': 'StackChan 配对' },
    h('legend', null, '设备配对'),
    h('p', null, '此页用于已安装 DSH.AGENT 的设备；原厂 AI.AGENT 不支持此配对流程。'),
    h('p', null, '读取编号、检查、写入和撤销会打开所选 USB 串口。写入和撤销还需在 Sion 的 Pairing 页点 Allow USB。'),
    h('button', { type: 'button', disabled: s.busy, onClick: () => controller.diagnose() }, '检查环境与查找配对选项'),
    h('p', null, '准备专用环境会在此 DSH 配置档下创建独立 Python 环境，离线安装随插件附带的 pySerial 3.5（BSD-3-Clause，约 91 KB）。需要已安装 Python 3.10 或更新版本；不更改全局 Python、设备权限或原厂绑定。'),
    h('button', { type: 'button', disabled: s.busy, onClick: () => controller.diagnose(true) }, '准备插件专用环境'),
    environment && h('section', { 'aria-label': '配对环境检查' },
      h('ul', null,
        h('li', null, environment.platform === 'macos' ? '系统：macOS。' : '当前系统尚不支持此设备配对工具。'),
        h('li', null, environment.pythonReady ? 'Python：满足版本要求。' : 'Python：需要 3.10 或更新版本。'),
        h('li', null, { unconfigured: '私有存储：尚未配置，请先完成插件安装设置。',
          absent: '私有存储：尚未创建，首次配对操作时创建。',
          private: '私有存储：目录权限符合要求；配对记录需另行刷新检查。',
          invalid: '私有存储：目录类型、归属或权限不符合要求。',
          unavailable: '私有存储：暂时无法检查。' }[environment.storage]),
        h('li', null, { available: 'USB 枚举：pySerial 可用。', missing: 'USB 枚举：所选 Python 缺少 pySerial。',
          unavailable: 'USB 枚举：检查失败，请检查 Python 环境。', not_checked: 'USB 枚举：系统或 Python 版本不支持，未检查。' }[environment.serial]),
        h('li', null, { available: '证书工具：OpenSSL 可运行；实际证书生成仍需验证。',
          missing: '证书工具：缺少 OpenSSL。', unavailable: '证书工具：OpenSSL 无法运行。' }[environment.openssl]),
        h('li', null, environment.deviceAccess ? '此安装已允许显式设备操作；写入仍需设备授权。' : environment.managedUsb ? '本配置档允许显式操作当前连接的 Espressif USB 串口；设备身份会另外核对。'
          : '此安装未允许设备操作。检查环境不会开启权限。')),
      h('label', { htmlFor: `${id}-ports` }, '候选 USB 串口'),
      h('select', { id: `${id}-ports`, disabled: s.busy || !environment.ports.length,
        value: environment.ports.some(p => p.path === s.port) ? s.port : '',
        onChange: e => controller.choosePort(e.target.value) },
        h('option', { value: '' }, '请选择端口，不会自动连接'),
        environment.ports.map(p => h('option', { key: p.path, value: p.path }, `${p.description || 'USB 设备'} — ${p.path}`))),
      environment.serial === 'available' && !environment.ports.length && h('p', null, '没有发现 USB 串口。检查数据线和连接后，可重新查找。'),
      environment.truncated && h('p', null, '候选较多，仅显示前 16 个；可手动填写明确的端口。'),
      h('p', null, '候选来自系统 USB 信息，不能证明它是 StackChan 或已安装 DSH.AGENT。')),
    h('button', { type: 'button', disabled: s.busy, onClick: () => controller.run('snapshot') }, '刷新本地配对状态'),
    snapshot && h('div', { role: 'status' },
      h('p', null, `本机身份：${snapshot.activePairId ? snapshot.activePairId.slice(-8) : '未配对'}；待安装身份：${snapshot.candidatePairId ? snapshot.candidatePairId.slice(-8) : '无'}`),
      snapshot.pending && h('p', null, '上次写入结果待核对。请先检查设备，不要重复写入。'),
      snapshot.observed && h('p', null, `上次设备状态：${snapshot.observed.state}。这不是当前在线状态。`)),
    field('deviceId', '设备编号', '12 位小写十六进制'),
    field('port', 'Mac USB 串口', '/dev/cu.…'),
    h('button', { type: 'button', disabled: s.busy || !s.port || !!snapshot?.deviceId,
      onClick: () => controller.run('identify') }, '读取设备编号'),
    h('p', null, '可从候选列表选择串口或手动填写。查找和选择不会打开串口。读取的编号仅填入配对草稿。'),
    h('label', { htmlFor: `${id}-without-lan` },
      h('input', { id: `${id}-without-lan`, type: 'checkbox', checked: s.withoutLan,
        disabled: s.busy, onChange: e => controller.edit('withoutLan', e.target.checked) }), ' 暂不配置局域网'),
    s.withoutLan && h('p', null, '需要 DSH.AGENT v50 或更新版本。可经 USB 使用，外出中继可另行配置。'),
    localNetwork && h('section', { 'aria-label': 'Mac 局域网地址' },
      h('label', { htmlFor: `${id}-addresses` }, '候选语音服务地址'),
      h('select', { id: `${id}-addresses`, disabled: s.busy || s.withoutLan || !localNetwork.endpoints.length,
        value: localNetwork.endpoints.some(endpoint => endpoint.url === s.localUrl) ? s.localUrl : '',
        onChange: e => controller.chooseLocalUrl(e.target.value) },
        h('option', { value: '' }, '请选择 Sion 可以访问的网络'),
        localNetwork.endpoints.map(endpoint => h('option', { key: endpoint.url, value: endpoint.url },
          `${endpoint.interfaceName} — ${endpoint.url}`))),
      localNetwork.status === 'unavailable' && h('p', null, '暂时无法读取 Mac 的网络接口，可手动填写。'),
      localNetwork.status === 'available' && !localNetwork.endpoints.length && h('p', null, '没有发现符合条件的局域网地址，可手动填写。'),
      localNetwork.truncated && h('p', null, '仅显示前 16 个局域网地址，可手动填写其他地址。')),
    field('localUrl', 'Mac 本地语音服务地址', 'wss://192.168.…:9080/audio'),
    h('p', null, '选择候选只填入地址。可修改建议端口 9080。设备能否连接，要在语音服务启动后确认。'),
    h('button', { type: 'button', disabled: s.busy || !snapshot || !!snapshot.pending,
      onClick: () => controller.run('prepare') }, '准备新的本机配对身份'),
    h('button', { type: 'button', disabled: s.busy || !snapshot,
      onClick: () => controller.run('inspect') }, '检查设备并核对结果'),
    h('label', { htmlFor: `${id}-confirm` }, h('input', { id: `${id}-confirm`, type: 'checkbox', checked: s.confirmed,
      disabled: s.busy, onChange: e => controller.edit('confirmed', e.target.checked) }),
    ' 我已核对设备，并在设备 Pairing 页点击 Allow USB'),
    h('div', { style: { display: 'flex', gap: 12 } },
      h('button', { type: 'button', disabled: s.busy || !s.confirmed || !snapshot?.candidatePairId || !!snapshot.pending,
        onClick: () => controller.run('install') }, '将配对身份写入设备'),
      h('button', { type: 'button', disabled: s.busy || !s.confirmed || !snapshot?.activePairId || !!snapshot.pending,
        onClick: () => controller.run('remove') }, '撤销本插件配对')),
    s.busy && h('p', { role: 'status' }, '正在处理，请等待结果…'),
    s.error && h('p', { role: 'alert' }, s.error),
    s.notice && h('p', { role: 'status' }, s.notice),
    h('p', null, '撤销本插件配对不会解绑原厂手机 App。私钥保存在 Mac 私有目录，不显示在页面中。'));
}
